/* ---------------------------------------------------------------------------
   map.js -- the choropleth surface.

   Two unit levels, both as plain GeoJSON sources: 4,135 PLSS townships (the
   primary analytic unit, because it comes free from the geocode and a Montanan
   can look up "T1S R26E") and 56 counties. No vector tiles and no PMTiles: the
   township layer is 158 KB gzipped once simplified at 50 m, which is 0.5% of a
   township's 9.6 km width and invisible at any zoom this dashboard uses.

   Colour is applied through `setFeatureState` rather than by rewriting the
   source, which keeps a repaint at a few milliseconds for 4,135 features.
   `removeFeatureState` is called before each repaint, or units keep a stale
   shade when they drop out of the current filter.

   A unit with no comparable data is painted in a distinct masked colour, never
   in the ramp's zero step: a reader cannot otherwise tell "no data" from
   "nothing happened", and conflating those is the easiest way to publish a
   false finding from this dataset.

   Above z10 the surface switches to ACTUAL PARCELS, served as a {z}/{x}/{y}
   tree of Mapbox Vector Tiles generated by GDAL -- 11,599 tiles, 118 MB, mean
   8 KB. A plain directory of files rather than PMTiles because Cloudflare Pages
   ignores HTTP Range, which breaks a single-archive format silently; 11,599
   files sits under the 20,000-asset cap. Zooms 6-9 were discarded: GDAL packs
   all 887,124 parcels into 9 tiles at z6, nearly 2 MB each, and the township
   choropleth is the right unit at those scales anyway.

   Parcel attributes are BAKED into the tiles (ladder stage, tenure, locality,
   acres, size class, and the snapshot index at which the parcel first appears),
   so colouring needs no client-side join and no feature-state at all -- just a
   data-driven paint expression.
--------------------------------------------------------------------------- */

import maplibregl from 'maplibre-gl';
import { Protocol as PMTilesProtocol } from 'pmtiles';

// The in-house basemap is one PMTiles archive read by HTTP Range through this
// protocol, registered once for the page.
maplibregl.addProtocol('pmtiles', new PMTilesProtocol().tile);

const MT_BOUNDS = [[-116.4, 44.2], [-103.9, 49.1]];

function cssv(name) {
  return getComputedStyle(document.documentElement).getPropertyValue(name).trim();
}

function mapLine() {
  const v = getComputedStyle(document.documentElement)
    .getPropertyValue('--map-line').trim();
  return v || '#a0967f';
}

/** The map's own ground, read from the theme so it does not stay light in dark mode. */
function siteBase() {
  return `${location.origin}${location.pathname.replace(/\/$/, '')}`;
}
// Labels are drawn from first-party glyphs (Noto Sans, vendored under
// /fonts), so the page fetches nothing from a third party by default.
function firstPartyGlyphs() {
  return `${siteBase()}/fonts/{fontstack}/{range}.pbf`;
}
function mapGround() {
  const v = getComputedStyle(document.documentElement)
    .getPropertyValue('--map-ground').trim();
  return v || '#ece5d5';
}
// Two basemaps, each in a light and a dark style so it follows the theme.
// 'montana' is the in-house one (basemap/ in the repository): State Library
// frameworks in one PMTiles archive under /basemap, which needs a host that
// honours HTTP Range -- Astro preview does, Cloudflare Pages static assets do
// not, so in production the archive lives on R2. 'positron' is OpenFreeMap,
// which serves the style JSON at the path itself (appending "/style.json"
// returns 404) and is the only thing on the page fetched from a third party.
function basemapStyle(kind, dark) {
  const theme = dark ? 'dark' : 'light';
  if (kind === 'montana') return `${siteBase()}/basemap/styles/${theme}.json`;
  return { light: 'https://tiles.openfreemap.org/styles/positron',
           dark: 'https://tiles.openfreemap.org/styles/dark' }[theme];
}

// Road widths by draw class (1 primary .. 5 track) and zoom; k scales the
// casing. Private roads and tracks have no casing, and draw in the casing
// grey rather than the road white so they stay quiet.
function roadWidth(k) {
  const w = (a, b, c, d) => ['match', ['get', 'cls'], 1, a * k, 2, b * k, 3, c * k, d * k];
  return ['interpolate', ['linear'], ['zoom'],
    10, w(1.6, 1.1, 0.5, 0.3), 13, w(4.5, 3.2, 1.8, 1.0), 15, w(9, 6.5, 4, 2.2)];
}
function roadColor() {
  return ['case', ['>=', ['get', 'cls'], 4], cssv('--road-case'), cssv('--road-fill')];
}
/** City polygons to one label point each (largest part's bbox centre, acres summed). */
function cityLabelPoints(fc) {
  const byName = new Map();
  for (const f of fc.features || []) {
    const name = f.properties?.name;
    if (!name) continue;
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates]
      : f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [];
    let best = null;
    for (const poly of polys) {
      let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
      for (const [x, y] of poly[0]) { if (x < x0) x0 = x; if (y < y0) y0 = y; if (x > x1) x1 = x; if (y > y1) y1 = y; }
      const area = (x1 - x0) * (y1 - y0);
      if (!best || area > best.area) best = { area, c: [(x0 + x1) / 2, (y0 + y1) / 2] };
    }
    if (!best) continue;
    const acres = Number(f.properties.acres) || 0;
    const cur = byName.get(name);
    if (!cur) byName.set(name, { ...best, acres, props: f.properties });
    else { cur.acres += acres; if (best.area > cur.area) { cur.area = best.area; cur.c = best.c; } }
  }
  return { type: 'FeatureCollection', features: Array.from(byName, ([name, v]) => ({
    type: 'Feature', geometry: { type: 'Point', coordinates: v.c },
    properties: { ...v.props, name, acres: v.acres } })) };
}

function labelPaint() {
  return { 'text-color': cssv('--ink-1') || '#1a1712',
           'text-halo-color': cssv('--page') || '#ffffff', 'text-halo-width': 1.3 };
}

export class UnitMap {
  constructor(container, { onSelect, onParcel } = {}) {
    this.onSelect = onSelect || (() => {});
    this.onParcel = onParcel || null;
    this.level = 'township';
    this.selected = new Set();
    this._painted = { township: false, county: false };

    this.map = new maplibregl.Map({
      container,
      // `glyphs` must be a string or absent: MapLibre rejects `glyphs:
      // undefined` outright and the whole page dies. The glyph server is
      // first-party (see firstPartyGlyphs); unit labels stay in the panel.
      style: {
        version: 8, sources: {}, glyphs: firstPartyGlyphs(), layers: [
          { id: 'bg', type: 'background', paint: { 'background-color': mapGround() } },
        ],
      },
      bounds: MT_BOUNDS, fitBoundsOptions: { padding: 18 },
      attributionControl: false, maxZoom: 15, minZoom: 4,
      dragRotate: false, pitchWithRotate: false,
    });
    this.map.addControl(new maplibregl.NavigationControl({ showCompass: false }), 'top-right');
    this.map.addControl(new maplibregl.AttributionControl({
      compact: true,
      customAttribution: 'Parcels & PLSS: Montana State Library / DOR',
    }), 'bottom-right');
    this.ready = new Promise((r) => this.map.on('load', r));
  }

  async init({ townships, counties }) {
    await this.ready;
    const m = this.map;
    this.overlayState = { parcels: true, reservations: false, publiclands: false,
                          townships: true, counties: true };
    m.addSource('twp', { type: 'geojson', data: townships, promoteId: 'tr_key' });
    m.addSource('cty', { type: 'geojson', data: counties, promoteId: 'county_n' });

    for (const [src, id] of [['twp', 'township'], ['cty', 'county']]) {
      m.addLayer({
        id: `${id}-fill`, type: 'fill', source: src,
        paint: {
          'fill-color': ['coalesce', ['feature-state', 'color'], 'rgba(0,0,0,0)'],
          // Fades out as the parcel layer takes over at z10, so the aggregate
          // surface hands off to the actual parcels rather than covering them.
          'fill-opacity': ['interpolate', ['linear'], ['zoom'],
            9.5, 0.88, 10.5, 0.12, 11.5, 0],
        },
      });
      m.addLayer({
        id: `${id}-line`, type: 'line', source: src,
        paint: {
          // County lines are the reference a reader orients by at lot scale,
          // so they are black (white in the dark theme) and thicken with zoom
          // instead of thinning into the parcel grid.
          'line-color': id === 'county' ? cssv('--county-line') : mapLine(),
          'line-width': id === 'county'
            ? ['interpolate', ['linear'], ['zoom'], 6, 0.9, 10, 1.5, 13, 2.6] : 0.35,
          'line-opacity': id === 'county' ? 0.9 : 0.5,
        },
      });
      // Selection is driven through a PAINT expression, not a filter:
      // MapLibre rejects feature-state in filters ("feature-state data
      // expressions are not supported with filters") and the error surfaces at
      // style-validation time, taking the map down with it.
      m.addLayer({
        id: `${id}-sel`, type: 'line', source: src,
        paint: {
          'line-color': getComputedStyle(document.documentElement)
            .getPropertyValue('--ink-1').trim() || '#1a1712',
          'line-width': 2.2,
          'line-opacity': ['case', ['boolean', ['feature-state', 'sel'], false], 1, 0],
        },
      });
      m.on('click', `${id}-fill`, (e) => {
        const f = e.features && e.features[0];
        if (f) this.onSelect(id, f.id, f.properties, e.originalEvent.shiftKey);
      });
      m.on('mouseenter', `${id}-fill`, () => { m.getCanvas().style.cursor = 'pointer'; });
      m.on('mouseleave', `${id}-fill`, () => { m.getCanvas().style.cursor = ''; });
    }
    // --- actual parcels, above z10 -------------------------------------
    m.addSource('parcels', {
      type: 'vector',
      tiles: [`${siteBase()}/data/parcels/{z}/{x}/{y}.pbf`],
      minzoom: 10, maxzoom: 12,
      // The same tiles carry the roads and buildings layers; only parcels
      // have a geocode to promote.
      promoteId: { parcels: 'id' },
    });
    // Parcel fills. (An outline-with-inward-band treatment was tried on
    // 2026-10-31 so a street basemap could read between parcels; at town
    // scale the bands outgrew the lots and the map lost legibility, so the
    // fill came back.) Roads and buildings are drawn above the fill as
    // first-party reference layers instead.
    m.addLayer({
      id: 'parcel-fill', type: 'fill', source: 'parcels', 'source-layer': 'parcels',
      minzoom: 10,
      paint: {
        'fill-color': cssv('--ord5-2') || '#b3774d',
        'fill-opacity': ['interpolate', ['linear'], ['zoom'], 10, 0.35, 11, 0.85],
      },
    });
    m.addLayer({
      id: 'parcel-line', type: 'line', source: 'parcels', 'source-layer': 'parcels',
      minzoom: 12.5,
      paint: { 'line-color': mapLine(), 'line-width': 0.4, 'line-opacity': 0.55 },
    });
    // --- reference layers from the same tiles: buildings, then roads -------
    // Building footprints: Microsoft's 2018 set statewide, the State Library's
    // lidar footprints where flown (src 2 and 3). A 2018 footprint inside a
    // flown area that the lidar did not see (src 4) is drawn at half strength:
    // it is either gone by the flight or missed by it. A neutral that reads
    // on any parcel colour. Roads are cased from z10 so they read on the
    // ground as well as on a fill; private roads and tracks are a faint
    // uncased line from z12.
    const unseen = ['==', ['get', 'src'], 4];
    m.addLayer({
      id: 'bld-fill', type: 'fill', source: 'parcels', 'source-layer': 'buildings',
      minzoom: 12.5,
      paint: { 'fill-color': cssv('--building'),
               'fill-opacity': ['interpolate', ['linear'], ['zoom'],
                 12.5, ['case', unseen, 0.18, 0.35], 14, ['case', unseen, 0.3, 0.6]] },
    });
    m.addLayer({
      id: 'road-case', type: 'line', source: 'parcels', 'source-layer': 'roads',
      minzoom: 10, layout: { 'line-cap': 'round', 'line-join': 'round' },
      filter: ['<=', ['get', 'cls'], 3],
      paint: { 'line-color': cssv('--road-case'), 'line-width': roadWidth(1.5), 'line-opacity': 0.9 },
    });
    m.addLayer({
      id: 'road-line', type: 'line', source: 'parcels', 'source-layer': 'roads',
      minzoom: 10, layout: { 'line-cap': 'round', 'line-join': 'round' },
      paint: { 'line-color': roadColor(), 'line-width': roadWidth(1),
               'line-opacity': ['interpolate', ['linear'], ['zoom'],
                 11, ['case', ['>=', ['get', 'cls'], 4], 0, 1],
                 12.5, ['case', ['>=', ['get', 'cls'], 4], 0.6, 1]] },
    });
    // Parcels first seen in the selected interval: magenta, a colour nothing
    // else on the map uses.
    m.addLayer({
      id: 'parcel-hl', type: 'line', source: 'parcels', 'source-layer': 'parcels',
      minzoom: 10, layout: { 'line-join': 'round' },
      filter: ['==', ['get', 'born'], -999],
      paint: { 'line-color': cssv('--created') || '#c4188f',
               'line-width': ['interpolate', ['linear'], ['zoom'], 10, 1.2, 13, 2.2, 15, 3] },
    });
    // The parcel fill is 85% opaque from z11 and had been hiding the county
    // line and the unit selection outlines beneath it; they ride on top.
    for (const id of ['county-line', 'township-sel', 'county-sel']) {
      if (m.getLayer(id)) m.moveLayer(id);
    }
    // The clicked parcel, so the reader knows which one the info box
    // describes: a cased outline that reads on any fill, selected by geocode
    // through a filter (the tiles carry no feature ids for feature-state).
    // Topmost, above the county line and the unit selection.
    m.addLayer({
      id: 'parcel-sel-case', type: 'line', source: 'parcels', 'source-layer': 'parcels',
      minzoom: 10, filter: ['==', ['get', 'id'], ''],
      layout: { 'line-join': 'round' },
      paint: { 'line-color': cssv('--page') || '#ffffff', 'line-width': 5.5, 'line-opacity': 0.95 },
    });
    m.addLayer({
      id: 'parcel-sel', type: 'line', source: 'parcels', 'source-layer': 'parcels',
      minzoom: 10, filter: ['==', ['get', 'id'], ''],
      layout: { 'line-join': 'round' },
      paint: { 'line-color': cssv('--ui') || '#04665e', 'line-width': 2.6 },
    });
    // Road names from the tiles, above everything but the selection.
    m.addLayer({
      id: 'road-label-major', type: 'symbol', source: 'parcels', 'source-layer': 'roads',
      minzoom: 10, filter: ['all', ['<=', ['get', 'cls'], 2], ['!=', ['get', 'name'], '']],
      layout: { 'symbol-placement': 'line', 'text-field': ['get', 'name'],
                'text-font': ['Noto Sans Bold'], 'text-max-angle': 30, 'text-padding': 4,
                'symbol-spacing': 420,
                'text-size': ['interpolate', ['linear'], ['zoom'], 10, 10, 14, 13] },
      paint: labelPaint(),
    }, 'parcel-sel-case');
    m.addLayer({
      id: 'road-label', type: 'symbol', source: 'parcels', 'source-layer': 'roads',
      minzoom: 12.5, filter: ['all', ['>=', ['get', 'cls'], 3], ['!=', ['get', 'name'], '']],
      layout: { 'symbol-placement': 'line', 'text-field': ['get', 'name'],
                'text-font': ['Noto Sans Regular'], 'text-max-angle': 30, 'text-padding': 3,
                'symbol-spacing': 320,
                'text-size': ['interpolate', ['linear'], ['zoom'], 12.5, 9.5, 15, 12] },
      paint: labelPaint(),
    }, 'parcel-sel-case');
    await this._loadReference();
    this.enforceOrder();
    m.on('click', 'parcel-fill', (e) => {
      const f = e.features && e.features[0];
      if (!f) return;
      this.selectParcel(f.properties.id);
      if (this.onParcel) this.onParcel(f.properties, e.lngLat);
    });
    m.on('mouseenter', 'parcel-fill', () => { m.getCanvas().style.cursor = 'pointer'; });
    m.on('mouseleave', 'parcel-fill', () => { m.getCanvas().style.cursor = ''; });

    this.setLevel('township');
  }

  /** One canonical stacking order, re-imposed after anything is added.
   *
   * Bottom to top: the ground, the external basemap if one is on, the unit
   * choropleth, parcels, the public-land wash, buildings and roads, the
   * boundary annotations (public-land edge, reservations, city limits), the
   * new-parcel outline, the county line, the unit selection, labels, and the
   * clicked parcel above everything. Layers are added in many places and at
   * many times, so the order is stated once here rather than at each add.
   */
  enforceOrder() {
    const m = this.map;
    const layers = m.getStyle().layers;
    const ids = new Set(layers.map((l) => l.id));
    const base = layers.filter((l) => l.id.startsWith('base-'));
    const order = [
      ...base.filter((l) => l.type !== 'symbol').map((l) => l.id),
      'township-fill', 'township-line', 'county-fill',
      'parcel-fill', 'parcel-line',
      'ov-publiclands-fill',
      'bld-fill', 'road-case', 'road-line', 'hwy-case', 'hwy-line',
      'ov-publiclands-line', 'ov-reservations-fill', 'ov-reservations-line', 'ov-cities-line',
      'parcel-hl',
      'county-line', 'township-sel', 'county-sel',
      'road-label-major', 'road-label', 'city-label-big', 'city-label-mid', 'city-label-small',
      ...base.filter((l) => l.type === 'symbol').map((l) => l.id),
      'parcel-sel-case', 'parcel-sel',
    ];
    for (const id of order) if (ids.has(id)) m.moveLayer(id);
  }

  /** Statewide highways for the zooms below the tiles, and city names. */
  async _loadReference() {
    const m = this.map;
    const base = siteBase();
    try {
      const r = await fetch(`${base}/data/highways.geojson`);
      if (r.ok && !m.getSource('hwy')) {
        m.addSource('hwy', { type: 'geojson', data: await r.json() });
        // Cased like the roads in the tiles, so they read as roads on the
        // choropleth rather than as another grid line.
        const hw = (k) => ['interpolate', ['linear'], ['zoom'],
          5, ['match', ['get', 'cls'], 1, 1.6 * k, 0.8 * k], 10, ['match', ['get', 'cls'], 1, 3.2 * k, 1.8 * k]];
        m.addLayer({
          id: 'hwy-case', type: 'line', source: 'hwy', maxzoom: 10.5,
          layout: { 'line-cap': 'round', 'line-join': 'round' },
          paint: { 'line-color': cssv('--road-case'), 'line-opacity': 0.9, 'line-width': hw(1.9) },
        }, m.getLayer('county-line') ? 'county-line' : undefined);
        m.addLayer({
          id: 'hwy-line', type: 'line', source: 'hwy', maxzoom: 10.5,
          layout: { 'line-cap': 'round', 'line-join': 'round' },
          paint: { 'line-color': cssv('--road-fill'), 'line-opacity': 1, 'line-width': hw(1) },
        }, m.getLayer('county-line') ? 'county-line' : undefined);
      }
    } catch (err) { console.warn('highways unavailable', err); }
    try {
      const r = await fetch(`${base}/data/cities.geojson`);
      if (r.ok && !m.getSource('cities')) {
        // One label point per city: MapLibre labels every part of a
        // multipart polygon, and a city annexed in pieces is several parts.
        // The point is the centre of the largest part's bounding box and
        // the acres are summed over the parts.
        m.addSource('cities', { type: 'geojson', data: cityLabelPoints(await r.json()) });
        // Big cities from z5, towns from z7, everything from z9.5: one layer
        // per tier with a filter, since a zero-size label still claims its
        // padding in collision and was knocking the big names out. The
        // largest place first in placement order.
        const tiers = [['big', ['>', ['get', 'acres'], 6000], 5],
                       ['mid', ['all', ['>', ['get', 'acres'], 1200], ['<=', ['get', 'acres'], 6000]], 7],
                       ['small', ['<=', ['get', 'acres'], 1200], 9.5]];
        for (const [tier, filter, minzoom] of tiers) {
          m.addLayer({
            id: `city-label-${tier}`, type: 'symbol', source: 'cities', minzoom, filter,
            layout: { 'symbol-placement': 'point', 'text-field': ['get', 'name'],
                      'text-font': ['Noto Sans Bold'], 'text-padding': 4,
                      'symbol-sort-key': ['-', 0, ['get', 'acres']],
                      'text-size': ['interpolate', ['linear'], ['zoom'], 5, 11.5, 9.5, 12, 12, 14] },
            paint: { ...labelPaint(), 'text-halo-width': 1.6 },
          }, m.getLayer('parcel-sel-case') ? 'parcel-sel-case' : undefined);
        }
      }
    } catch (err) { console.warn('city names unavailable', err); }
  }

  /** Roads (with their names) or buildings, on or off. */
  setReference(kind, on) {
    const ids = kind === 'roads'
      ? ['road-case', 'road-line', 'road-label-major', 'road-label', 'hwy-case', 'hwy-line']
      : ['bld-fill'];
    for (const id of ids) {
      if (this.map.getLayer(id)) this.map.setLayoutProperty(id, 'visibility', on ? 'visible' : 'none');
    }
  }

  /** Outline one parcel by geocode; an empty id clears the outline. */
  selectParcel(id) {
    this.selectedParcel = id || '';
    for (const l of ['parcel-sel-case', 'parcel-sel']) {
      if (this.map.getLayer(l)) this.map.setFilter(l, ['==', ['get', 'id'], this.selectedParcel]);
    }
  }

  /** Reference overlays, fetched only when first switched on. */
  async addOverlay(kind, url) {
    const m = this.map;
    if (m.getSource(`ov-${kind}`)) return true;
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${kind}: HTTP ${res.status}`);
    m.addSource(`ov-${kind}`, { type: 'geojson', data: await res.json() });
    // Public land is the edge of the private universe the holdings views
    // measure, so it is drawn as land: the conventional forest-service green,
    // translucent enough for the parcel surface and basemap to read through.
    // It sits ABOVE the parcel fill -- that fill is 85% opaque at parcel zoom
    // and used to hide the overlay entirely -- and below the highlight and
    // selection outlines. (A 16% grey wash beneath the parcels was tried
    // first and was invisible wherever it mattered.) The seven reservations
    // are few and large, so they read best as an annotation: an outline, no
    // fill.
    if (kind === 'publiclands') {
      const above = ['bld-fill', 'parcel-hl', 'township-line'].find((id) => m.getLayer(id));
      m.addLayer({
        id: 'ov-publiclands-fill', type: 'fill', source: 'ov-publiclands',
        paint: { 'fill-color': cssv('--public-land'), 'fill-opacity': 0.38 },
      }, above);
      m.addLayer({
        id: 'ov-publiclands-line', type: 'line', source: 'ov-publiclands',
        paint: { 'line-color': cssv('--public-land'), 'line-width': 0.6,
                 'line-opacity': ['interpolate', ['linear'], ['zoom'], 8, 0.3, 11, 0.75] },
      }, above);
    } else if (kind === 'cities') {
      // City limits are annotation too: a dashed outline in a colour nothing
      // else on the map uses, no fill, above the parcels so the limit stays
      // legible at lot scale, where it is the question most often asked.
      const above = ['bld-fill', 'parcel-hl', 'township-line'].find((id) => m.getLayer(id));
      m.addLayer({
        id: 'ov-cities-line', type: 'line', source: 'ov-cities',
        paint: { 'line-color': cssv('--city-limit'), 'line-dasharray': [3, 1.5],
                 'line-width': ['interpolate', ['linear'], ['zoom'], 6, 1.0, 10, 2.0, 13, 3.2],
                 'line-opacity': 1 },
      }, above);
    } else {
      m.addLayer({
        id: 'ov-reservations-fill', type: 'fill', source: 'ov-reservations',
        paint: { 'fill-color': cssv('--cat-2'), 'fill-opacity': 0.06 },
      }, 'township-line');
      m.addLayer({
        id: 'ov-reservations-line', type: 'line', source: 'ov-reservations',
        paint: { 'line-color': cssv('--cat-2'), 'line-width': 2, 'line-opacity': 0.95 },
      });
    }
    this.enforceOrder();
    return true;
  }

  setOverlay(kind, on) {
    const vis = on ? 'visible' : 'none';
    for (const sfx of ['fill', 'line']) {
      const id = `ov-${kind}-${sfx}`;
      if (this.map.getLayer(id)) this.map.setLayoutProperty(id, 'visibility', vis);
    }
  }

  setParcelsVisible(on) {
    for (const id of ['parcel-fill', 'parcel-line', 'parcel-hl', 'parcel-sel-case', 'parcel-sel']) {
      if (this.map.getLayer(id)) {
        this.map.setLayoutProperty(id, 'visibility', on ? 'visible' : 'none');
      }
    }
  }

  /** Data-driven paint for the parcel layer, plus an optional highlight filter. */
  setParcelPaint(colorExpr, highlightFilter) {
    if (this.map.getLayer('parcel-fill')) {
      this.map.setPaintProperty('parcel-fill', 'fill-color', colorExpr);
    }
    if (this.map.getLayer('parcel-hl')) {
      this.map.setFilter('parcel-hl', highlightFilter || ['==', ['get', 'born'], -999]);
    }
  }

  get zoom() { return this.map.getZoom(); }

  setLevel(level) {
    this.level = level;
    for (const id of ['township', 'county']) {
      const on = id === level ? 'visible' : 'none';
      for (const sfx of ['fill', 'sel']) {
        if (this.map.getLayer(`${id}-${sfx}`)) {
          this.map.setLayoutProperty(`${id}-${sfx}`, 'visibility', on);
        }
      }
      // County outlines stay visible beneath the township surface for orientation.
      if (this.map.getLayer(`${id}-line`)) {
        this.map.setLayoutProperty(`${id}-line`, 'visibility',
          id === 'county' ? 'visible' : on);
      }
    }
  }

  get source() { return this.level === 'township' ? 'twp' : 'cty'; }

  /** Repaint from a Map of featureId -> css colour. Stale state is cleared first. */
  paint(colors) {
    const src = this.source;
    if (this._painted[this.level]) this.map.removeFeatureState({ source: src });
    this._painted[this.level] = true;
    for (const [id, color] of colors) {
      this.map.setFeatureState({ source: src, id }, { color });
    }
    this.applySelection();
  }

  applySelection() {
    const src = this.source;
    for (const id of this.selected) {
      this.map.setFeatureState({ source: src, id }, { sel: true });
    }
  }

  setSelection(ids) {
    const src = this.source;
    for (const id of this.selected) {
      if (!ids.has(id)) this.map.setFeatureState({ source: src, id }, { sel: false });
    }
    this.selected = new Set(ids);
    this.applySelection();
  }

  /** Swap between the external basemap and a first-party outlines-only view.
   *
   * The basemap is additive and opt-in: its sources and non-symbol layers are
   * grafted BENEATH our own, so the page renders fully from first-party data if
   * the origin is unavailable or blocked.
   *
   * Two details matter. The style declares more than one source -- a raster
   * relief layer AND the vector tiles the layers actually reference -- so every
   * source must be registered and each layer's `source` remapped; taking the
   * first key alone grafts the raster and every vector layer then fails with
   * "requires a vector source". The style's glyph and sprite endpoints are
   * adopted so its label layers can be used: they ride ABOVE the parcels, so
   * street and place names stay legible, and below the selection outlines.
   */
  async setBasemap(kind) {
    const m = this.map;
    this._basemapKind = kind;
    // Always tear down first: switching themes reloads in the other variant.
    for (const id of this._baseLayers || []) {
      if (m.getLayer(id)) m.removeLayer(id);
    }
    for (const id of this._baseSources || []) {
      if (m.getSource(id)) m.removeSource(id);
    }
    this._baseLayers = [];
    this._baseSources = [];
    if (kind === 'none') { m.setGlyphs(firstPartyGlyphs()); return; }

    const dark = document.documentElement.getAttribute('data-theme') === 'dark'
      || (!document.documentElement.getAttribute('data-theme')
          && window.matchMedia('(prefers-color-scheme: dark)').matches);
    try {
      const res = await fetch(basemapStyle(kind, dark));
      if (!res.ok) throw new Error(`HTTP ${res.status}`);
      const style = await res.json();

      if (style.glyphs) m.setGlyphs(style.glyphs);
      if (style.sprite) m.setSprite(style.sprite);
      const srcMap = {};
      for (const [name, def] of Object.entries(style.sources || {})) {
        const id = `base-src-${name}`;
        if (!m.getSource(id)) m.addSource(id, def);
        srcMap[name] = id;
        this._baseSources.push(id);
      }
      // Graft beneath our own fills so the choropleth stays on top.
      const beneath = ['township-fill', 'county-fill']
        .find((id) => m.getLayer(id));
      const labelsBefore = ['parcel-sel-case', 'township-sel'].find((id) => m.getLayer(id));
      for (const layer of style.layers || []) {
        if (layer.type === 'background') continue;
        const src = srcMap[layer.source];
        if (!src) continue;
        const id = `base-${layer.id}`;
        m.addLayer({ ...layer, id, source: src }, layer.type === 'symbol' ? labelsBefore : beneath);
        this._baseLayers.push(id);
      }
      // Our own fills become translucent so the basemap reads through.
      for (const id of ['township-fill', 'county-fill']) {
        if (m.getLayer(id)) {
        m.setPaintProperty(id, 'fill-opacity', ['interpolate', ['linear'], ['zoom'],
          9.5, 0.62, 10.5, 0.1, 11.5, 0]);
      }
      }
    } catch (err) {
      console.warn('basemap unavailable; outlines only', err);
      this._basemapKind = 'none';
    }
    this.enforceOrder();
    if (kind === 'none' || this._basemapKind === 'none') {
      for (const id of ['township-fill', 'county-fill']) {
        if (m.getLayer(id)) {
          m.setPaintProperty(id, 'fill-opacity', ['interpolate', ['linear'], ['zoom'],
            9.5, 0.88, 10.5, 0.12, 11.5, 0]);
        }
      }
    }
  }

  fitTo(bbox) { if (bbox) this.map.fitBounds(bbox, { padding: 30, maxZoom: 11 }); }

  /** Re-read themed colours after a light/dark switch. */
  retheme() {
    // Reload the external basemap in the matching variant, if one is active.
    if (this._basemapKind && this._basemapKind !== 'none') {
      const kind = this._basemapKind;
      this.setBasemap('none');
      this.setBasemap(kind);
    }
    if (this.map.getLayer('bg')) {
      this.map.setPaintProperty('bg', 'background-color', mapGround());
    }
    const line = getComputedStyle(document.documentElement)
      .getPropertyValue('--map-line').trim() || '#a0967f';
    if (this.map.getLayer('township-line')) this.map.setPaintProperty('township-line', 'line-color', line);
    if (this.map.getLayer('county-line')) this.map.setPaintProperty('county-line', 'line-color', cssv('--county-line'));
    if (this.map.getLayer('parcel-hl')) this.map.setPaintProperty('parcel-hl', 'line-color', cssv('--created') || '#c4188f');
    for (const [id, prop, tok] of [['bld-fill', 'fill-color', '--building'], ['road-case', 'line-color', '--road-case'],
                                   ['hwy-case', 'line-color', '--road-case'], ['hwy-line', 'line-color', '--road-fill']]) {
      if (this.map.getLayer(id)) this.map.setPaintProperty(id, prop, cssv(tok));
    }
    if (this.map.getLayer('road-line')) this.map.setPaintProperty('road-line', 'line-color', roadColor());
    for (const id of ['road-label-major', 'road-label', 'city-label-big', 'city-label-mid', 'city-label-small']) {
      if (!this.map.getLayer(id)) continue;
      const lp = labelPaint();
      this.map.setPaintProperty(id, 'text-color', lp['text-color']);
      this.map.setPaintProperty(id, 'text-halo-color', lp['text-halo-color']);
    }
    if (this.map.getLayer('parcel-sel-case')) this.map.setPaintProperty('parcel-sel-case', 'line-color', cssv('--page') || '#ffffff');
    if (this.map.getLayer('parcel-sel')) this.map.setPaintProperty('parcel-sel', 'line-color', cssv('--ui') || '#04665e');
    const sel = getComputedStyle(document.documentElement)
      .getPropertyValue('--ink-1').trim() || '#1a1712';
    for (const id of ['township-sel', 'county-sel']) {
      if (this.map.getLayer(id)) this.map.setPaintProperty(id, 'line-color', sel);
    }
    // Overlays were coloured when loaded; re-read their tokens too.
    for (const [id, tok] of [['ov-publiclands-fill', '--public-land'], ['ov-publiclands-line', '--public-land'],
                             ['ov-reservations-fill', '--cat-2'], ['ov-reservations-line', '--cat-2'],
                             ['ov-cities-line', '--city-limit']]) {
      if (!this.map.getLayer(id)) continue;
      this.map.setPaintProperty(id, id.endsWith('-fill') ? 'fill-color' : 'line-color', cssv(tok));
    }
  }
}

/** Quantile breaks, so a skewed distribution still fills the ramp. */
export function quantileBreaks(values, nClasses) {
  const v = Array.from(values).filter((x) => isFinite(x) && x > 0).sort((a, b) => a - b);
  if (!v.length) return [];
  const out = [];
  for (let i = 1; i < nClasses; i++) out.push(v[Math.floor((i / nClasses) * v.length)]);
  return out.filter((x, i, a) => i === 0 || x > a[i - 1]);
}

export function classify(value, breaks) {
  let i = 0;
  while (i < breaks.length && value >= breaks[i]) i++;
  return i;
}
